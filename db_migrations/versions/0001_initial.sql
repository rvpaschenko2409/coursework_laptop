CREATE FUNCTION touch_project() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 NEW.revision := OLD.revision+1;
 NEW.updated_at := now();
 RETURN NEW;
END $$;
CREATE TRIGGER tr_project_revision BEFORE UPDATE ON projects
 FOR EACH ROW EXECUTE FUNCTION touch_project();
CREATE FUNCTION bump_project() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN
   UPDATE projects SET updated_at=now() WHERE id=OLD.project_id;
   RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' AND NEW.project_id<>OLD.project_id THEN
   RAISE EXCEPTION 'Moving a row to another project is not allowed';
 END IF;
 UPDATE projects SET updated_at=now() WHERE id=NEW.project_id;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_criteria_revision AFTER INSERT OR UPDATE OR DELETE ON criteria
 FOR EACH ROW EXECUTE FUNCTION bump_project();
CREATE TRIGGER tr_alternatives_revision AFTER INSERT OR UPDATE OR DELETE ON alternatives
 FOR EACH ROW EXECUTE FUNCTION bump_project();
CREATE TRIGGER tr_scores_revision AFTER INSERT OR UPDATE OR DELETE ON scores
 FOR EACH ROW EXECUTE FUNCTION bump_project();
CREATE TRIGGER tr_comparisons_revision AFTER INSERT OR UPDATE OR DELETE ON comparisons
 FOR EACH ROW EXECUTE FUNCTION bump_project();
CREATE TRIGGER tr_stakeholders_revision AFTER INSERT OR UPDATE OR DELETE ON stakeholders
 FOR EACH ROW EXECUTE FUNCTION bump_project();

-- A deferred constraint also rejects an incomplete set at transaction commit.
CREATE FUNCTION check_weight_sum() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE set_id bigint; total numeric; n integer;
BEGIN
 IF TG_TABLE_NAME='weight_sets' THEN set_id:=NEW.id;
 ELSIF TG_OP='DELETE' THEN set_id:=OLD.weight_set_id;
 ELSE set_id:=NEW.weight_set_id;
 END IF;
 IF EXISTS(SELECT 1 FROM weight_sets WHERE id=set_id) THEN
   SELECT coalesce(sum(value),0),count(*) INTO total,n FROM weights WHERE weight_set_id=set_id;
   IF n<2 OR abs(total-1)>0.000001 THEN
     RAISE EXCEPTION USING MESSAGE = 'Weights must contain at least 2 criteria and sum to 1, got ' || total::text;
   END IF;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER tr_weight_set_sum AFTER INSERT OR UPDATE ON weight_sets
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_weight_sum();
CREATE CONSTRAINT TRIGGER tr_weights_sum AFTER INSERT OR UPDATE OR DELETE ON weights
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_weight_sum();
CREATE FUNCTION freeze_finished_result() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.status IN ('succeeded','failed') THEN
   RAISE EXCEPTION 'Finished results are immutable; create a new result';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_results_frozen BEFORE UPDATE ON results
 FOR EACH ROW EXECUTE FUNCTION freeze_finished_result();

CREATE FUNCTION guard_weight_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='UPDATE' AND (NEW.weight_set_id<>OLD.weight_set_id OR NEW.criterion_id<>OLD.criterion_id OR NEW.project_id<>OLD.project_id) THEN
   RAISE EXCEPTION 'Weight identity cannot be changed';
 END IF;
 IF TG_OP='DELETE' THEN
   PERFORM 1 FROM weight_sets WHERE id=OLD.weight_set_id FOR UPDATE;
   RETURN OLD;
 END IF;
 PERFORM 1 FROM weight_sets WHERE id=NEW.weight_set_id FOR UPDATE;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_weights_identity BEFORE INSERT OR UPDATE OR DELETE ON weights
 FOR EACH ROW EXECUTE FUNCTION guard_weight_identity();
CREATE FUNCTION record_score_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.value,NEW.source,NEW.prediction_id) IS DISTINCT FROM (OLD.value,OLD.source,OLD.prediction_id) THEN
   IF NEW.expert_id IS NULL OR NEW.override_reason IS NULL OR length(btrim(NEW.override_reason))=0 THEN
     RAISE EXCEPTION 'Score change requires an actor and a reason';
   END IF;
   INSERT INTO score_history(project_id,score_id,old_value,new_value,old_source,new_source,prediction_id,actor_id,reason)
   VALUES(OLD.project_id,OLD.id,OLD.value,NEW.value,OLD.source,NEW.source,OLD.prediction_id,NEW.expert_id,NEW.override_reason);
 END IF;
 NEW.updated_at:=now();
 RETURN NEW;
END $$;
CREATE TRIGGER tr_scores_history BEFORE UPDATE ON scores
 FOR EACH ROW EXECUTE FUNCTION record_score_change();
CREATE FUNCTION protect_prediction() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (to_jsonb(NEW)-'explanation') IS DISTINCT FROM (to_jsonb(OLD)-'explanation') THEN
   RAISE EXCEPTION 'Prediction inputs and value are immutable; create a new prediction';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_predictions_frozen BEFORE UPDATE ON predictions
 FOR EACH ROW EXECUTE FUNCTION protect_prediction();
