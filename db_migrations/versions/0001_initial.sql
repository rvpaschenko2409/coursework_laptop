CREATE TYPE opt_direction AS ENUM ('max', 'min');
CREATE TYPE value_source AS ENUM ('manual', 'ml', 'calc');
CREATE TYPE project_role AS ENUM ('analyst', 'decision_maker', 'expert');
CREATE TYPE data_layer AS ENUM ('raw', 'staging', 'processed');
CREATE TYPE data_split AS ENUM ('train', 'valid', 'test');
CREATE TYPE task_status AS ENUM ('queued', 'running', 'succeeded', 'failed');
CREATE DOMAIN positive_finite AS double precision
 CHECK (VALUE > 0 AND VALUE < 'Infinity'::double precision);
CREATE DOMAIN finite_number AS double precision
 CHECK (VALUE > '-Infinity'::double precision AND VALUE < 'Infinity'::double precision);

CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(254) NOT NULL CHECK (email = lower(btrim(email)) AND position('@' in email)>1),
 password_hash text NOT NULL CHECK (length(password_hash)>20),
 name varchar(200) NOT NULL CHECK (length(btrim(name))>0),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(email)
);
CREATE TABLE projects (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id bigint NOT NULL REFERENCES users(id) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
 title varchar(200) NOT NULL CHECK (length(btrim(title))>0),
 goal text NOT NULL DEFAULT '',
 budget positive_finite,
 status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','archived')),
 settings jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(settings)='object'),
 catwoe jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(catwoe)='object'),
 root_definition text NOT NULL DEFAULT '',
 revision bigint NOT NULL DEFAULT 1 CHECK(revision>0),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE project_members (
 project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
 role project_role NOT NULL,
 invited_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(project_id,user_id)
);
CREATE TABLE criteria (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 code varchar(50) NOT NULL,
 name varchar(200) NOT NULL CHECK(length(btrim(name))>0),
 unit varchar(50) NOT NULL DEFAULT '',
 direction opt_direction NOT NULL,
 scale_type text NOT NULL DEFAULT 'ratio' CHECK(scale_type='ratio'),
 source value_source NOT NULL DEFAULT 'manual',
 sort_order integer NOT NULL DEFAULT 0 CHECK(sort_order>=0),
 UNIQUE(project_id,id), UNIQUE(project_id,code), UNIQUE(project_id,name)
);
CREATE TABLE alternatives (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 code varchar(50) NOT NULL,
 name varchar(200) NOT NULL CHECK(length(btrim(name))>0),
 description text NOT NULL DEFAULT '',
 features jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(features)='object'),
 sort_order integer NOT NULL DEFAULT 0 CHECK(sort_order>=0),
 UNIQUE(project_id,id), UNIQUE(project_id,code)
);
CREATE TABLE stakeholders (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 name varchar(200) NOT NULL,
 stakeholder_role text NOT NULL DEFAULT '',
 interests text NOT NULL DEFAULT '',
 power smallint NOT NULL CHECK(power BETWEEN 1 AND 5),
 legitimacy smallint NOT NULL CHECK(legitimacy BETWEEN 1 AND 5),
 urgency smallint NOT NULL CHECK(urgency BETWEEN 1 AND 5),
 salience numeric(5,3) GENERATED ALWAYS AS
   (round((power+legitimacy+urgency)::numeric/3,3)) STORED,
 UNIQUE(project_id,name)
);
CREATE TABLE datasets (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 parent_dataset_id bigint,
 name varchar(200) NOT NULL,
 origin text NOT NULL CHECK(origin IN ('synthetic','open','manual')),
 source_url text,
 license text NOT NULL,
 sha256 char(64) NOT NULL CHECK(sha256 ~ '^[0-9a-f]{64}$'),
 seed bigint,
 generator_version text,
 generation_params jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(generation_params)='object'),
 quality_report jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(quality_report)='object'),
 row_count integer NOT NULL CHECK(row_count BETWEEN 0 AND 10000),
 column_count integer NOT NULL CHECK(column_count>0),
 uploaded_by bigint NOT NULL REFERENCES users(id) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
 uploaded_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(project_id,id), UNIQUE(project_id,sha256),
 FOREIGN KEY(project_id,parent_dataset_id) REFERENCES datasets(project_id,id) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
 CHECK(origin<>'synthetic' OR (seed IS NOT NULL AND generator_version IS NOT NULL)),
 CHECK(parent_dataset_id IS NULL OR parent_dataset_id<>id)
);
-- The split belongs to a clean configuration, not to a noisy row.
CREATE TABLE dataset_groups (
 dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE CASCADE,
 configuration_id text NOT NULL CHECK(length(configuration_id)>0),
 split data_split NOT NULL,
 PRIMARY KEY(dataset_id,configuration_id),
 UNIQUE(dataset_id,configuration_id,split)
);
CREATE TABLE dataset_rows (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dataset_id bigint NOT NULL REFERENCES datasets(id) ON DELETE CASCADE,
 layer data_layer NOT NULL,
 row_number integer NOT NULL CHECK(row_number>0),
 configuration_id text,
 split data_split,
 data jsonb NOT NULL CHECK(jsonb_typeof(data)='object'),
 provenance jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(provenance)='object'),
 UNIQUE(dataset_id,layer,row_number),
 FOREIGN KEY(dataset_id,configuration_id,split)
   REFERENCES dataset_groups(dataset_id,configuration_id,split) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
 CHECK(layer<>'processed' OR (configuration_id IS NOT NULL AND split IS NOT NULL))
);
